#!/usr/bin/env node
/*
 * Regenerates lib/db-selects.generated.ts — the list of selects the health
 * check probes.
 *
 * Hand-maintaining that list would defeat the point. The 2026-08-12 outage
 * happened because a query broke somewhere nobody was looking; a registry
 * that only holds the queries somebody remembered to add has the same hole.
 * So it is generated from the source, and tests/db-selects.test.ts fails if
 * the committed file has drifted from what the source now contains.
 *
 *   npm run selects:sync
 */
import { writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

// The scanner is TypeScript, so this script is run through tsx
// (`npm run selects:sync`). Importing it here rather than registering a
// loader keeps the entry point working under both `tsx` and the test runner.
const { findSelects, resolveConstants, isUnresolved } = await import(
  "../lib/db-select-scan.ts"
);

/*
 * A select declared as a shared constant has no `.from()` next to it, so the
 * table cannot be read off the source. These are the files that declare one.
 * A new file declaring a select constant is a hard error rather than a silent
 * skip — skipping is how a query ends up unwatched.
 */
const CONST_TABLES = {
  "lib/sessions/queries.ts": "sessions",
  "lib/videos/queries.ts": "videos",
};

export function buildRegistry() {
  // EVERY select, not only the ones that embed. The embed-only version
  // missed lib/activity.ts asking enrollments for a `created_at` that has
  // never existed — a plain column list, failing silently for months.
  const found = findSelects();
  const entries = new Map();
  const problems = [];

  for (const f of found) {
    const select = resolveConstants(f.select);
    if (isUnresolved(select)) {
      // An interpolation we cannot resolve would be sent to PostgREST as
      // literal "${...}" and fail for the wrong reason.
      continue;
    }
    const table = f.table ?? CONST_TABLES[f.file];
    if (!table) {
      problems.push(
        `${f.file} declares a select constant with an embed, but no table is ` +
          `mapped for it in scripts/sync-db-selects.mjs (CONST_TABLES).`,
      );
      continue;
    }
    const key = `${table}::${select}`;
    if (!entries.has(key)) entries.set(key, { table, select, file: f.file });
  }

  if (problems.length > 0) {
    throw new Error(problems.join("\n"));
  }
  return [...entries.values()].sort((a, b) =>
    a.table === b.table
      ? a.select.localeCompare(b.select)
      : a.table.localeCompare(b.table),
  );
}

export function renderRegistry(entries) {
  const rows = entries
    .map(
      (e) =>
        `  // ${e.file}\n` +
        `  { table: ${JSON.stringify(e.table)}, select: ${JSON.stringify(e.select)} },`,
    )
    .join("\n");
  return `// GENERATED by scripts/sync-db-selects.mjs — do not edit by hand.
// Run \`npm run selects:sync\` after changing any select.
// tests/db-selects.test.ts fails when this file is stale.
//
// Every select the app performs. lib/health.ts runs each one against the
// database every 6 hours, so a query that stops resolving is reported
// instead of waiting to be discovered by whoever loads the page.

export interface ProbedSelect {
  table: string;
  select: string;
}

export const PROBED_SELECTS: ProbedSelect[] = [
${rows}
];
`;
}

const OUT = "lib/db-selects.generated.ts";

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const entries = buildRegistry();
  writeFileSync(OUT, renderRegistry(entries));
  console.log(`${OUT}: ${entries.length} selects`);
}
